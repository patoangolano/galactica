import net.minecraft.resources.Identifier;
import net.minecraft.world.phys.AABB;

/**
 * Optional GeckoLib 5.5.7 renderer for the Starship. Every GeckoLib reference in the mod lives in this class, which
 * {@code ShipClient} only touches when GeckoLib {@code >=5.5.7 <5.6} is loaded (and falls back to the built-in renderer on a
 * {@link LinkageError}); without GeckoLib the vanilla
 * {@link StarshipRenderer} draws the same model.
 *
 * <p>The ship entity stays a plain {@code VehicleEntity}: it is rendered through {@link GeoReplacedEntityRenderer}
 * with one shared {@link ShipAnimatable}, and GeckoLib keeps a separate animation manager per entity id. Assets
 * come from {@code assets/galactica/geckolib/models/entity/ship.geo.json} and
 * {@code .../animations/entity/ship.animation.json}, both generated by {@code assets-src/ship/gen_starship.py}.
 * <ul>
 *   <li>controller {@code gear}: plays {@code gear.retract}/{@code gear.extend} when the ship's gear command flips
 *       (altitude and ground contact, {@link dev.galactica.ship.ShipAnimator#gearDown});</li>
 *   <li>controller {@code canopy}: {@code canopy.open} while nobody is aboard, {@code canopy.close} once boarded;</li>
 *   <li>nozzle gimbal: posed every frame from the thrust-vector state in {@link #adjustModelBonesForRender}.</li>
 * </ul>
 * The geometry holds only the opaque hull layer; the canopy glass, the cockpit interior, the emissive lights and
 * engine cores, and the exhaust, are drawn by the shared vanilla code on top, from the same part table, so nothing
 * is drawn twice.
 */
public final class GeckoShipRendering {
    private GeckoShipRendering() {}

    private static final String[] GEAR_BONES = {"gear_front", "gear_left", "gear_right"};

    static final DataTicket<Boolean> GEAR_DOWN = DataTicket.create("galactica_ship_gear_down", Boolean.class);
    static final DataTicket<Boolean> CANOPY_OPEN = DataTicket.create("galactica_ship_canopy_open", Boolean.class);

    private static final RawAnimation GEAR_RETRACT = RawAnimation.begin().thenPlayAndHold("gear.retract");
    private static final RawAnimation GEAR_EXTEND = RawAnimation.begin().thenPlayAndHold("gear.extend");
    private static final RawAnimation CANOPY_OPEN_ANIM = RawAnimation.begin().thenPlayAndHold("canopy.open");
    private static final RawAnimation CANOPY_CLOSE_ANIM = RawAnimation.begin().thenPlayAndHold("canopy.close");

    /** The GeckoLib Starship renderer; called from the renderer provider, so link errors surface at bake. */
    public static EntityRenderer<Starship, ?> create(EntityRendererProvider.Context context) {
        return new Renderer(context);
    }

    /** The single animatable every Starship is drawn with (GeckoLib keys its state by entity id). */
    static final class ShipAnimatable implements GeoAnimatable {
        private final AnimatableInstanceCache cache = GeckoLibUtil.createInstanceCache(this);

        @Override
        public void registerControllers(AnimatableManager.ControllerRegistrar controllers) {
            controllers.add(new AnimationController<ShipAnimatable>("gear", 0, GeckoShipRendering::gear));
            controllers.add(new AnimationController<ShipAnimatable>("canopy", 0, GeckoShipRendering::canopy));
        }

        @Override
        public AnimatableInstanceCache getAnimatableInstanceCache() {
            return cache;
        }
    }

    private static PlayState gear(AnimationTest<ShipAnimatable> test) {
        boolean down = test.getDataOrDefault(GEAR_DOWN, Boolean.TRUE);
        return test.setAndContinue(down ? GEAR_EXTEND : GEAR_RETRACT);
    }

    private static PlayState canopy(AnimationTest<ShipAnimatable> test) {
        boolean open = test.getDataOrDefault(CANOPY_OPEN, Boolean.FALSE);
        return test.setAndContinue(open ? CANOPY_OPEN_ANIM : CANOPY_CLOSE_ANIM);
    }

    static final class Model extends GeoModel<ShipAnimatable> {
        private static final Identifier GEO = Galactica.id("entity/ship");

        @Override
        public Identifier getModelResource(GeoRenderState state) {
            return GEO;
        }

        @Override
        public Identifier getTextureResource(GeoRenderState state) {
            return StarshipRenderer.TEXTURE;
        }

        @Override
        public Identifier getAnimationResource(ShipAnimatable animatable) {
            return GEO;
        }
    }

    static final class Renderer extends GeoReplacedEntityRenderer<ShipAnimatable, Starship, StarshipRenderState> {
        private final StarshipRenderer.Layers layers;

        Renderer(EntityRendererProvider.Context context) {
            super(context, new Model(), new ShipAnimatable());
            this.layers = StarshipRenderer.Layers.bake(context);
            this.shadowRadius = 3.5F;
        }

        @Override
        public StarshipRenderState createRenderState() {
            return new StarshipRenderState();
        }

        @Override
        public StarshipRenderState createRenderState(ShipAnimatable animatable, Starship ship) {
            return new StarshipRenderState();
        }

        @Override
        public void addRenderData(ShipAnimatable animatable, Starship ship, StarshipRenderState state, float partialTick) {
            StarshipRenderer.extractShip(ship, state, partialTick);
            // EntityRenderState implements GeoRenderState through GeckoLib's mixin; that interface injection is not
            // visible to a compileOnly dependency, hence this cast and the raw RenderPassInfo parameters below.
            GeoRenderState geo = (GeoRenderState) state;
            geo.addGeckolibData(GEAR_DOWN, ship.gearCommandedDown());
            geo.addGeckolibData(CANOPY_OPEN, ShipAnimator.canopyOpen(ship.getPassengers().size()));
        }

        /** Full attitude about the hull centre instead of GeckoLib's body-yaw turn. */
        @Override
        @SuppressWarnings("rawtypes")
        protected void applyRotations(RenderPassInfo info, PoseStack pose, float scale) {
            StarshipRenderState s = (StarshipRenderState) info.renderState();
            pose.translate(0F, StarshipRenderer.PIVOT_BLOCKS, 0F);
            pose.rotate(s.attitude);
            pose.translate(0F, -StarshipRenderer.PIVOT_BLOCKS, 0F);
        }

        @Override
        @SuppressWarnings("rawtypes")
        public void adjustModelBonesForRender(RenderPassInfo info, BoneSnapshots bones) {
            StarshipRenderState s = (StarshipRenderState) info.renderState();
            float yaw = (float) Math.toRadians(s.gimbalYaw), pitch = (float) Math.toRadians(s.gimbalPitch);
            bones.ifPresent("nozzle_left", b -> b.setRotation(pitch, yaw, 0F));
            bones.ifPresent("nozzle_right", b -> b.setRotation(pitch, yaw, 0F));
            // Stowed legs sit inside the pods and nose; hide them once folded, as the built-in model does.
            boolean stowed = ShipAnimator.ease(1F - s.gear) >= 0.98F;
            for (String leg : GEAR_BONES) bones.ifPresent(leg, b -> b.skipRender(stowed).skipChildrenRender(stowed));
            // From the cockpit the exterior canopy hoops would cut across the view; the shared code draws the interior.
            boolean inside = s.cockpitView;
            bones.ifPresent("canopy", b -> b.skipRender(inside).skipChildrenRender(inside));
        }

        @Override
        protected AABB getBoundingBoxForCulling(Starship ship, float partialTicks) {
            return StarshipRenderer.cullingBox(ship);
        }

        @Override
        public void submit(StarshipRenderState state, PoseStack pose, SubmitNodeCollector out, CameraRenderState camera) {
            super.submit(state, pose, out, camera);
            StarshipRenderer.submitOverlays(state, pose, out, camera, layers);
        }
    }
}
